    sets_data = scryfall_data.get("data", [])
    for s in sets_data:
        stype = s.get("set_type")
        if stype in ("core", "expansion", "masters", "draft_innovation", "funny"):
            name = s.get("name")
            code = s.get("code", "").upper()
